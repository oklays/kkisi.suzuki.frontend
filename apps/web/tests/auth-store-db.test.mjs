async function realWorld(extraEnv = {}) {
  const pw = JSON.parse(readFileSync(FIXTURE, 'utf8'));
  const authDb = authClient(), legacyDb = legacyClient();
  const config = loadAuthConfig({ ...ENV, DATABASE_URL: LEGACY_URL, DATABASE_URL_AUTH: AUTH_URL, ...extraEnv }); const keys = buildKeys(config.secrets);
  const logs = []; const l = (e, f) => logs.push({ e, ...f });
  const verifier = new WorkerPasswordVerifier({ workers: 2, maxQueue: 8 });
  const services = { config, keys, deps: {
    clock: { now: () => new Date() }, random: { bytes: (n) => randomBytes(n) }, identity: sessionIdentity, log: l,
    users: new PrismaUserRepository(legacyDb, l), permissions: new PrismaPermissionRepository(legacyDb, l), companies: new PrismaCompanyRepository(legacyDb, l), registers: new PrismaRegisterRepository(legacyDb, l),
    sessions: new PrismaSessionStore(authDb, l), throttle: new PrismaThrottleStore(authDb, l), verifier, throttleKeys: (u, ip) => keys.throttleKeys(u, ip) } };
  return { services, pw, logs, close: () => verifier.close(), authDb };
}
const post = (services, handler, path, body, o = {}) => handler(services, makeRequest(path, { method: 'POST', body, ...o }));

test('FULL STACK on a real MariaDB (synthetic identities): login, session, register, branch rules, logout persistence, lockout, generic failures', options, async () => {
  const world = await realWorld(); const { services, pw } = world; await freshAuthDb();
  try {
    const login = (u, p, o) => post(services, handleLogin, '/api/auth/login', { username: u, password: p }, o);
    // generic failures are byte-identical: unknown, wrong password, disabled, inactive role, inactive branch
    const shapes = new Set();
    for (const [u, p] of [['ghost', 'x'], ['synth_kasir1', 'wrong'], ['synth_off', pw.off], ['synth_kepala', pw.kepala], ['synth_nobranch', pw.nobranch]]) { const r = await login(u, p); assert.equal(r.status, 401, u); shapes.add(await r.text() + JSON.stringify([...r.headers].filter(([k]) => k !== 'set-cookie'))); }
    assert.equal(shapes.size, 1);
    assert.deepEqual(new Set(world.logs.filter((x) => x.e === 'login_failed').map((x) => x.reason)), new Set(['bad_credentials', 'role_inactive', 'company_inactive']));

    const ok = await login('synth_kasir1', pw.kasir1); assert.equal(ok.status, 200);
    const cookie = cookieOf(ok), token = (await bodyOf(ok)).csrfToken;
    const me = await bodyOf(await handleSession(services, makeRequest('/api/auth/session', { cookie })));
    assert.equal(me.user.roleId, 4); assert.equal(me.company.name, 'SYNTH BRANCH 1'); assert.equal(me.canSwitchBranch, false);
    const reg = await bodyOf(await handleRegister(services, makeRequest('/api/pos/register', { cookie })));
    assert.equal(reg.open.noref, 'KRS-S-1'); assert.deepEqual(reg.kasir, [{ id: 1, noKasir: 'KRS01' }]);
    assert.equal((await post(services, handleCompany, '/api/auth/company', { companyId: 2 }, { cookie, token })).status, 403, 'role 4 cannot change branch');

    // role <= 2: may choose a branch, but not while a register is open elsewhere
    const kop = await login('synth_koperasi', pw.koperasi); const kc = cookieOf(kop), kt = (await bodyOf(kop)).csrfToken;
    assert.equal((await post(services, handleCompany, '/api/auth/company', { companyId: 3 }, { cookie: kc, token: kt })).status, 403, 'open register in branch 2');
    assert.equal((await post(services, handleCompany, '/api/auth/company', { companyId: 2 }, { cookie: kc, token: kt })).status, 200);
    const kreg = await bodyOf(await handleRegister(services, makeRequest('/api/pos/register', { cookie: kc })));
    assert.equal(kreg.open.noref, 'KRS-S-2', 'the register read follows the SESSION branch');
    const stale = await login('synth_kasir2', pw.kasir2); const st = await bodyOf(await handleRegister(services, makeRequest('/api/pos/register', { cookie: cookieOf(stale) })));
    assert.equal(st.open.stale, true);

    // logout is persistent: a brand-new set of services (a "restart") still refuses the id
    assert.equal((await post(services, handleLogout, '/api/auth/logout', {}, { cookie, token })).status, 200);
    const restarted = await realWorld();
    try { assert.equal((await handleSession(restarted.services, makeRequest('/api/auth/session', { cookie }))).status, 401); } finally { await restarted.close(); }
    assert.equal((await handleSession(services, makeRequest('/api/auth/session', { cookie: kc }))).status, 200, 'other sessions unaffected');

    // 10 wrong passwords lock the username persistently, even for the right password; another user is unaffected
    for (let i = 0; i < 10; i++) await login('synth_admin', 'wrong' + i);
    const locked = await login('synth_admin', pw.admin); assert.equal(locked.status, 429); assert.ok(Number(locked.headers.get('retry-after')) > 0);
    assert.equal((await login('synth_kasir1', pw.kasir1)).status, 200);
    const stored = await world.authDb.$queryRaw`SELECT kind, failures FROM kkisi_auth_staging.auth_throttle`;
    assert.deepEqual([...new Set(stored.map((r) => r.kind))], ['user'], 'only user keys exist without a trusted proxy');
    for (const row of await world.authDb.$queryRaw`SELECT HEX(sid_hash) AS h FROM kkisi_auth_staging.auth_session`) assert.equal(String(row.h).length, 64);
  } finally { await world.close(); }
});
