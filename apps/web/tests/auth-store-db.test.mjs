test('REAL session store: 8 simultaneous logins by one user with a pool of 8 connections keep exactly 5 valid sessions, no failures', options, async () => {
  const db = authClient(); await db.$executeRawUnsafe('DELETE FROM kkisi_auth_staging.auth_session');
  const s = new PrismaSessionStore(db, log); const { createHash } = await import('node:crypto'); const now = new Date();
  const results = await Promise.allSettled(Array.from({ length: 8 }, (_, i) => s.create({ sidHash: createHash('sha256').update('c' + i).digest(), userId: 77, companyId: 1, pwf: 'bb'.repeat(8), now, idleExpiresAt: new Date(now.getTime() + 7200e3), absExpiresAt: new Date(now.getTime() + 43200e3), purgeAfter: new Date(now.getTime() + 129600e3) })));
  assert.equal(results.filter((r) => r.status === 'fulfilled').length, 8, JSON.stringify(results.filter((r) => r.status === 'rejected').map((r) => String(r.reason?.message))));
  const valid = num((await db.$queryRaw`SELECT COUNT(*) AS n FROM kkisi_auth_staging.auth_session WHERE user_id = 77 AND revoked_at IS NULL`)[0].n);
  assert.equal(valid, 5);
});

test('REAL throttle store: threshold, fixed window restart, exact counting under 100 parallel failures, cleared by success, purge bounded', options, async () => {
  const db = await freshAuthDb(); const th = new PrismaThrottleStore(db, log); const t0 = new Date('2026-10-01T08:00:00Z');
  const key = { kind: 'user', keyHash: Buffer.alloc(32, 9) };
  const rec = (now, limit = 3) => th.recordFailure({ key, limit, now, windowMs: WINDOW_MS, lockMs: LOCK_MS, purgeAfter: new Date(now.getTime() + THROTTLE_PURGE_MS) });
  await rec(t0); await rec(new Date(t0.getTime() + 120e3)); assert.deepEqual(await th.activeLocks([key], new Date(t0.getTime() + 130e3)), []);
  await rec(new Date(t0.getTime() + 240e3));
  const locks = await th.activeLocks([key], new Date(t0.getTime() + 250e3)); assert.equal(locks.length, 1); assert.equal(locks[0].lockedUntil.getTime(), t0.getTime() + 240e3 + LOCK_MS);
  await rec(new Date(t0.getTime() + 40 * 60e3));                        // after the window: counter restarts at 1
  assert.equal(num((await db.$queryRaw`SELECT failures AS n FROM kkisi_auth_staging.auth_throttle`)[0].n), 1);
  await th.clear([key]); assert.equal(num((await db.$queryRaw`SELECT COUNT(*) AS n FROM kkisi_auth_staging.auth_throttle`)[0].n), 0);
  const th2 = new PrismaThrottleStore(db, log);
  const k2 = { kind: 'user', keyHash: Buffer.alloc(32, 7) };
  await Promise.all(Array.from({ length: 100 }, () => th2.recordFailure({ key: k2, limit: LIMITS.user, now: t0, windowMs: WINDOW_MS, lockMs: LOCK_MS, purgeAfter: new Date(t0.getTime() + THROTTLE_PURGE_MS) })));
  assert.equal(num((await db.$queryRaw`SELECT failures AS n FROM kkisi_auth_staging.auth_throttle WHERE key_hash = ${k2.keyHash}`)[0].n), 100, 'no lost update');
  assert.equal((await th2.activeLocks([k2], new Date(t0.getTime() + 1000))).length, 1);
  for (let i = 0; i < 25; i++) await th.recordFailure({ key: { kind: 'ip', keyHash: Buffer.alloc(32, 20 + i) }, limit: 30, now: t0, windowMs: WINDOW_MS, lockMs: LOCK_MS, purgeAfter: new Date(t0.getTime() - 1) });
  assert.equal(await th.purge(t0, 10), 10); assert.equal(await th.purge(t0, 100), 15);
  await th.clear([k2]);
});

test('REAL throttle store: an impossible lock (10 years ahead, e.g. after a clock jump) is ignored and removed', options, async () => {
  const db = await freshAuthDb(); const th = new PrismaThrottleStore(db, log); const now = new Date('2026-10-01T08:00:00Z'); const key = { kind: 'user', keyHash: Buffer.alloc(32, 5) };
  await db.$executeRaw`INSERT INTO kkisi_auth_staging.auth_throttle (key_hash,kind,failures,first_failure_at,last_failure_at,locked_until,purge_after) VALUES (${key.keyHash},'user',10,${now},${now},${new Date('2036-10-01T08:00:00Z')},${new Date('2036-10-01T10:00:00Z')})`;
  assert.deepEqual(await th.activeLocks([key], now), []);
  assert.equal(num((await db.$queryRaw`SELECT COUNT(*) AS n FROM kkisi_auth_staging.auth_throttle WHERE key_hash = ${key.keyHash} AND locked_until IS NOT NULL AND locked_until > ${new Date('2030-01-01')}`)[0].n), 0, 'the bogus lock was removed');
});

