-- FA-04 loan decision: the legacy mobile loan request table, STRUCTURE ONLY, exactly as in the 30 Sep 2026 production dump (no index on doc_no).
CREATE TABLE IF NOT EXISTS `__KOSIPA_DB__`.`trans_pinjaman_pengajuan` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `doc_no` varchar(50) DEFAULT NULL,
  `doc_date` date DEFAULT NULL,
  `doc_status` varchar(50) DEFAULT NULL,
  `status_pencairan` enum('OPEN','APPROVED') DEFAULT NULL,
  `tgl_pencairan` date DEFAULT NULL,
  `doc_remarks` varchar(255) DEFAULT NULL,
  `nik_kar` varchar(50) DEFAULT NULL,
  `nama` varchar(50) DEFAULT NULL,
  `gaji` double(18,2) DEFAULT NULL,
  `bagian` varchar(100) DEFAULT NULL,
  `jenis_pinjaman_id` int(11) DEFAULT NULL,
  `jenis_pinjaman` varchar(50) DEFAULT NULL,
  `total_pinjaman` decimal(18,4) DEFAULT 0.0000,
  `lama_angsuran` int(11) DEFAULT 0,
  `foto_ktp` text DEFAULT NULL,
  `foto_slip_gaji` text DEFAULT NULL,
  `foto_npwp` text DEFAULT NULL,
  `no_rek` varchar(50) DEFAULT NULL,
  `nama_rek` varchar(50) DEFAULT NULL,
  `bank_rek` varchar(50) DEFAULT NULL,
  `cd` datetime DEFAULT NULL,
  `cd_usr` varchar(50) DEFAULT NULL,
  `ud` datetime DEFAULT NULL,
  `ud_usr` varchar(50) DEFAULT NULL,
  `created_at` datetime DEFAULT NULL,
  `updated_at` datetime DEFAULT NULL,
  `is_payroll` int(11) NOT NULL,
  `jenis_pencairan` varchar(100) DEFAULT NULL,
  `tanda_tangan` varchar(100) DEFAULT NULL,
  `keterangan_riject` text DEFAULT NULL,
  `is_online` int(11) NOT NULL DEFAULT 1,
  `foto_kk` varchar(255) DEFAULT NULL,
  `foto_bukti_biaya_sekolah` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=latin1 COLLATE=latin1_swedish_ci ROW_FORMAT=COMPACT;
